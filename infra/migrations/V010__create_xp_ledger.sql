-- ── XP Ledger (append-only, partitioned) ─────────────────
CREATE TABLE xp_ledger (
 id UUID DEFAULT gen_random_uuid(),
 user_id UUID NOT NULL,
 amount INT NOT NULL,
 type TEXT NOT NULL,
 ref_id UUID,
 community_id UUID,
 created_at TIMESTAMPTZ DEFAULT now()
) PARTITION BY RANGE (created_at);

